/**
 * Generates the app icon from one geometric description:
 *   assets/icon.svg                      master icon (rounded square, for stores/README)
 *   assets/icon-foreground.svg           glyph only, adaptive-icon safe zone
 *   android/.../drawable/ic_launcher_foreground.xml   vector, adaptive foreground
 *   android/.../drawable/ic_launcher_background.xml   vector, adaptive background
 *   android/.../drawable/ic_launcher_monochrome.xml   vector, Android 13 themed icon
 *   android/.../mipmap-*\/ic_launcher{,_round}.png     legacy PNGs (API < 26)
 *
 * Run: node scripts/make-icons.mjs   (PNG rendering needs `playwright` resolvable;
 * pass --no-png to only write the vector files.)
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const TEAL = '#0D7A8F';
const TEAL_LIGHT = '#139AB2';
const TEAL_DARK = '#0A6274';
const WHITE = '#FFFFFF';

// All geometry is in the 108x108 adaptive-icon grid. The launcher mask keeps the
// centre 72dp; every glyph point stays inside the 33dp safe circle.
function roundRect(x, y, w, h, r) {
  return (
    `M${x + r},${y}h${w - 2 * r}a${r},${r} 0 0 1 ${r},${r}v${h - 2 * r}a${r},${r} 0 0 1 ${-r},${r}` +
    `h${-(w - 2 * r)}a${r},${r} 0 0 1 ${-r},${-r}v${-(h - 2 * r)}a${r},${r} 0 0 1 ${r},${-r}z`
  );
}
// A rounded rect with a rounded rectangular hole (an "empty checkbox"), even-odd fill.
function hollowBox(x, y, s, r, t) {
  return roundRect(x, y, s, s, r) + roundRect(x + t, y + t, s - 2 * t, s - 2 * t, Math.max(0.5, r - t));
}

const ROWS = [37, 54, 71];
const BOX_X = 31;
const BOX = 12;
const BAR_X = 49;
const BAR_H = 5.5;
const BAR_W = [23, 28, 19];

/** [{ d, fill, fillRule?, stroke?, strokeWidth?, opacity? }] */
function glyph(color = WHITE, tickColor = TEAL) {
  const shapes = [];
  ROWS.forEach((cy, i) => {
    const by = cy - BOX / 2;
    if (i === 0) {
      shapes.push({ d: roundRect(BOX_X, by, BOX, BOX, 2.6), fill: color });
      shapes.push({
        d: `M${BOX_X + 2.8},${cy + 0.3}l3.1,3.1l5.6,-6.5`,
        stroke: tickColor,
        strokeWidth: 2.4,
        fill: 'none',
      });
    } else {
      shapes.push({ d: hollowBox(BOX_X, by, BOX, 2.6, 2), fill: color, fillRule: 'evenodd' });
    }
    shapes.push({
      d: roundRect(BAR_X, cy - BAR_H / 2, BAR_W[i], BAR_H, BAR_H / 2),
      fill: color,
      opacity: i === 0 ? 0.72 : 1,
    });
  });
  return shapes;
}

function svgPath(s) {
  const attrs = [`d="${s.d}"`, `fill="${s.fill}"`];
  if (s.fillRule) attrs.push(`fill-rule="${s.fillRule}"`);
  if (s.stroke) attrs.push(`stroke="${s.stroke}" stroke-width="${s.strokeWidth}" stroke-linecap="round" stroke-linejoin="round"`);
  if (s.opacity !== undefined && s.opacity !== 1) attrs.push(`opacity="${s.opacity}"`);
  return `  <path ${attrs.join(' ')}/>`;
}

function vectorPath(s) {
  const a = [`android:pathData="${s.d}"`];
  a.push(`android:fillColor="${s.fill === 'none' ? '#00000000' : s.fill}"`);
  if (s.fillRule) a.push(`android:fillType="${s.fillRule}"`);
  if (s.stroke) a.push(`android:strokeColor="${s.stroke}" android:strokeWidth="${s.strokeWidth}" android:strokeLineCap="round" android:strokeLineJoin="round"`);
  if (s.opacity !== undefined && s.opacity !== 1) a.push(`android:fillAlpha="${s.opacity}"`);
  return `    <path\n        ${a.join('\n        ')} />`;
}

const gradientDefs = `
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="${TEAL_LIGHT}"/>
      <stop offset="1" stop-color="${TEAL_DARK}"/>
    </linearGradient>
  </defs>`;

// ---- Master SVG: the visible 72dp area of the adaptive icon, as a rounded square.
const CROP = 18; // (108-72)/2
const master = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${CROP} ${CROP} 72 72" width="512" height="512">${gradientDefs}
  <rect x="${CROP}" y="${CROP}" width="72" height="72" rx="16" fill="url(#bg)"/>
${glyph().map(svgPath).join('\n')}
</svg>
`;
const round = master.replace(`<rect x="${CROP}" y="${CROP}" width="72" height="72" rx="16"`, `<circle cx="54" cy="54" r="36"`);

const foregroundSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="432" height="432">
${glyph().map(svgPath).join('\n')}
</svg>
`;

const header = `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/make-icons.mjs; edit that file, not this one. -->\n`;
const vector = (body, extraNs = '') =>
  `${header}<vector xmlns:android="http://schemas.android.com/apk/res/android"${extraNs}\n    android:width="108dp"\n    android:height="108dp"\n    android:viewportWidth="108"\n    android:viewportHeight="108">\n${body}\n</vector>\n`;

const foregroundXml = vector(glyph().map(vectorPath).join('\n'));
const monochromeXml = vector(glyph('#000000', '#000000').map(vectorPath).join('\n'));
const backgroundXml = vector(
  `    <path android:pathData="M0,0h108v108h-108z">\n        <aapt:attr name="android:fillColor">\n            <gradient android:type="linear" android:startX="54" android:startY="0" android:endX="54" android:endY="108">\n                <item android:offset="0" android:color="${TEAL_LIGHT}" />\n                <item android:offset="1" android:color="${TEAL_DARK}" />\n            </gradient>\n        </aapt:attr>\n    </path>`,
  '\n    xmlns:aapt="http://schemas.android.com/aapt"',
);

const RES = 'android/app/src/main/res';
mkdirSync('assets', { recursive: true });
writeFileSync('assets/icon.svg', master);
writeFileSync('assets/icon-round.svg', round);
writeFileSync('assets/icon-foreground.svg', foregroundSvg);
writeFileSync(`${RES}/drawable/ic_launcher_foreground.xml`, foregroundXml);
writeFileSync(`${RES}/drawable/ic_launcher_background.xml`, backgroundXml);
writeFileSync(`${RES}/drawable/ic_launcher_monochrome.xml`, monochromeXml);
for (const name of ['ic_launcher', 'ic_launcher_round']) {
  writeFileSync(
    `${RES}/mipmap-anydpi-v26/${name}.xml`,
    `${header}<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n    <background android:drawable="@drawable/ic_launcher_background"/>\n    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n</adaptive-icon>\n`,
  );
}
console.log('wrote SVGs and vector drawables');

if (process.argv.includes('--no-png')) process.exit(0);

// ---- Legacy PNGs for API < 26 (Capacitor minSdk is 24).
const DENSITIES = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
let chromium;
try {
  const require = createRequire(import.meta.url);
  const candidates = [process.env.PLAYWRIGHT_PATH, 'playwright'].filter(Boolean);
  for (const c of candidates) {
    try {
      ({ chromium } = require(c));
      break;
    } catch {
      /* try next */
    }
  }
  if (!chromium) throw new Error('playwright not found (set PLAYWRIGHT_PATH or run with --no-png)');
} catch (e) {
  console.error(String(e));
  process.exit(1);
}
const browser = await chromium.launch();
const page = await browser.newPage();
for (const [density, px] of Object.entries(DENSITIES)) {
  for (const [name, svg] of [
    ['ic_launcher', master],
    ['ic_launcher_round', round],
  ]) {
    await page.setViewportSize({ width: px, height: px });
    await page.setContent(`<body style="margin:0;background:transparent">${svg.replace('width="512" height="512"', `width="${px}" height="${px}"`)}</body>`);
    const buf = await page.screenshot({ omitBackground: true, clip: { x: 0, y: 0, width: px, height: px } });
    writeFileSync(`${RES}/mipmap-${density}/${name}.png`, buf);
  }
}
await browser.close();
console.log('rendered legacy PNGs');
